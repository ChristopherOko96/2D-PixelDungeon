// Exports the hell monsters from hell_monsters.js for the Godot game:
//   assets/sprites/hell/monsters/<id>.png  one atlas per monster, a row per animation,
//                                           a column per frame, each pixel scaled up by px
//   assets/data/hell_monsters.json          names, sizes, animation rows, stats, attacks, floors
// Usage: node tools/hell_dungeon/export_monsters.js [repo_root] [--only id,id,...]
//   --only writes just those atlases and replaces just those entries of the existing
//   hell_monsters.json (every other entry, the floors and the key order stay as they are),
//   e.g. --only drache1,drache2,drache3,drache4 after a change to Ignaroth's art.
'use strict';
const fs = require('fs');
const path = require('path');
const HM = require('./hell_monsters.js');
const { encodePng } = require('./monster_sheet.js');

const args = process.argv.slice(2);
const root = args.find(a => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--only') || path.join(__dirname, '..', '..');
const onlyAt = args.indexOf('--only');
const only = onlyAt >= 0 ? String(args[onlyAt + 1] || '').split(',').filter(Boolean) : null;
if (only) for (const id of only) if (!HM.DEFS[id]) throw new Error('--only: unknown monster ' + id);
const spriteDir = path.join(root, 'assets', 'sprites', 'hell', 'monsters');
const jsonPath = path.join(root, 'assets', 'data', 'hell_monsters.json');
fs.mkdirSync(spriteDir, { recursive: true });

/** Writes the atlas of monster id and returns its hell_monsters.json entry. */
function exportMonster(id) {
  const def = HM.DEFS[id];
  // frames are scaled up by a whole number so the game draws them with little filtering; a def
  // may set its own px (Ignaroth's large frames: see hell_monsters.js drakeDef)
  const px = def.px || Math.ceil(def.scale);
  const anims = HM.ANIMS.filter(a => a === 'death' || def.anims[a]);
  const cols = Math.max(...anims.map(a => HM.frameCount(def, a)));
  const fw = def.w * px, fh = def.h * px, W = fw * cols, H = fh * anims.length;
  const out = new Uint8Array(W * H * 4);
  const rows = {};
  anims.forEach((a, row) => {
    const n = HM.frameCount(def, a);
    rows[a] = { row, frames: n };
    for (let f = 0; f < n; f++) {
      const r = HM.render(id, a, f);
      if (r.w !== def.w || r.h !== def.h) throw new Error(`${id} ${a} ${f}: frame ${r.w}x${r.h}, def ${def.w}x${def.h}`);
      for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) {
        const i = (y * r.w + x) * 4;
        if (!r.data[i + 3]) continue;
        for (let dy = 0; dy < px; dy++) for (let dx = 0; dx < px; dx++) {
          const o = ((row * fh + y * px + dy) * W + f * fw + x * px + dx) * 4;
          out[o] = r.data[i]; out[o + 1] = r.data[i + 1]; out[o + 2] = r.data[i + 2]; out[o + 3] = 255;
        }
      }
    }
  });
  fs.writeFileSync(path.join(spriteDir, id + '.png'), encodePng(W, H, out));
  console.log(id, `${def.w}x${def.h} px ${px} -> ${W}x${H}`);
  // functions (draw, frame), the death colours (ash, baked into the atlas) and the own px stay
  // out; px goes last, as it always has
  const { draw, frame, ash, px: ownPx, ...plain } = def;
  return Object.assign(plain, { px, anims: rows });
}

let data;
if (only) {
  data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  for (const id of only) data.defs[id] = exportMonster(id);
} else {
  const defs = {};
  for (const id in HM.DEFS) defs[id] = exportMonster(id);
  const floors = {};
  for (const n in HM.FLOORS) floors[n] = HM.FLOORS[n];
  data = { note: 'Generated by tools/hell_dungeon/export_monsters.js from hell_monsters.js; do not edit by hand.', defs, floors };
}
fs.writeFileSync(jsonPath, JSON.stringify(data, null, 1) + '\n');
console.log((only || Object.keys(data.defs)).length, 'monsters ->', spriteDir);
