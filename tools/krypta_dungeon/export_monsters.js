// Exports the crypt monsters (Story 1) from krypta_monsters.js for the Godot game, like
// tools/hell_dungeon/export_monsters.js does for the hell:
//   assets/sprites/krypta/monsters/<id>.png  one atlas per monster, a row per animation, a column per frame
//   assets/data/krypta_monsters.json          names, sizes, animation rows, stats, attacks, floors
// Usage: node tools/krypta_dungeon/export_monsters.js [repo_root]
'use strict';
const fs = require('fs');
const path = require('path');
const HM = require("./krypta_monsters.js");
const { encodePng } = require("../hell_dungeon/monster_sheet.js");

const root = process.argv[2] || path.join(__dirname, '..', '..');
const spriteDir = path.join(root, "assets", "sprites", "krypta", "monsters");
fs.mkdirSync(spriteDir, { recursive: true });

const defs = {};
for (const id in HM.DEFS) {
  const def = HM.DEFS[id];
  // frames are scaled up by a whole number so the game draws them with little filtering
  const px = Math.ceil(def.scale);
  const anims = HM.ANIMS.filter(a => a === 'death' || def.anims[a]);
  const cols = Math.max(...anims.map(a => HM.frameCount(def, a)));
  const fw = def.w * px, fh = def.h * px, W = fw * cols, H = fh * anims.length;
  const out = new Uint8Array(W * H * 4);
  const rows = {};
  anims.forEach((a, row) => {
    const n = HM.frameCount(def, a);
    rows[a] = { row, frames: n };
    for (let f = 0; f < n; f++) {
      const r = HM.render(id, a, f);
      for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) {
        const i = (y * r.w + x) * 4;
        if (!r.data[i + 3]) continue;
        for (let dy = 0; dy < px; dy++) for (let dx = 0; dx < px; dx++) {
          const o = ((row * fh + y * px + dy) * W + f * fw + x * px + dx) * 4;
          out[o] = r.data[i]; out[o + 1] = r.data[i + 1]; out[o + 2] = r.data[i + 2]; out[o + 3] = 255;
        }
      }
    }
  });
  fs.writeFileSync(path.join(spriteDir, id + '.png'), encodePng(W, H, out));
  const { draw, ...plain } = def;
  defs[id] = Object.assign(plain, { px, anims: rows });
}
const floors = {};
for (const n in HM.FLOORS) floors[n] = HM.FLOORS[n];
const data = { note: 'Generated by tools/krypta_dungeon/export_monsters.js from krypta_monsters.js; do not edit by hand.', defs, floors };
fs.writeFileSync(path.join(root, "assets", "data", "krypta_monsters.json"), JSON.stringify(data, null, 1) + '\n');
console.log(Object.keys(defs).length, 'monsters ->', spriteDir);
