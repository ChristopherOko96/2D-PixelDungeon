"""Packs the Story 1 crypt figures (0x72 frames, Leerenrufer and bomber) into krypta_pix.js.

krypta_monsters.js paints every crypt monster from these pixels, so the browser preview and a
later Godot sheet export need no image decoder. Format per frame: w, h, a palette of hex
colours and one character per pixel ('.' = transparent, else an index into the palette).

Usage (repo root): py -3 -I tools/krypta_dungeon/make_pix.py tools/krypta_dungeon/krypta_pix.js
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'hell_dungeon'))
import img  # noqa: E402

ROOT = os.path.join(HERE, '..', '..', 'assets', 'sprites')
NAMES = (['0x72/skelet_idle_anim_f%d' % i for i in range(4)] + ['0x72/skelet_run_anim_f%d' % i for i in range(4)]
         + ['0x72/necromancer_idle_anim_f%d' % i for i in range(4)] + ['0x72/necromancer_run_anim_f%d' % i for i in range(4)]
         + ['0x72/tiny_zombie_idle_anim_f%d' % i for i in range(4)] + ['0x72/tiny_zombie_run_anim_f%d' % i for i in range(4)]
         + ['0x72/ice_zombie_anim_f0', '0x72/big_zombie_idle_anim_f0', '0x72/skull']
         + ['0x72/chest_mimic_open_anim_f%d' % i for i in range(3)]
         + ['void/void_body_f%d' % i for i in range(8)] + ['void/void_bomber_f%d' % i for i in range(8)]
         + ['0x72/weapon_%s' % w for w in ('rusty_sword', 'knight_sword', 'mace', 'bow', 'arrow', 'red_magic_staff', 'green_magic_staff', 'big_hammer')])
CHARS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+,-/:;<=>?@[]^_{|}~'


def pack(im):
    pal, out = [], []
    for y in range(im.h):
        for x in range(im.w):
            r, g, b, a = im.get(x, y)
            if a < 128:
                out.append('.')
                continue
            c = '#%02x%02x%02x' % (r, g, b)
            if c not in pal:
                pal.append(c)
            out.append(CHARS[pal.index(c)])
    assert len(pal) <= len(CHARS)
    return {'w': im.w, 'h': im.h, 'pal': pal, 'px': ''.join(out)}


def main():
    data = {}
    for n in NAMES:
        data[n.split('/')[-1]] = pack(img.load(os.path.join(ROOT, n + '.png')))
    js = ('// Generated by tools/krypta_dungeon/make_pix.py from assets/sprites/0x72 and assets/sprites/void. Do not edit.\n'
          '(function (root) { const PIX = ' + json.dumps(data, separators=(',', ':')) + ';\n'
          "  if (typeof module === 'object' && module.exports) module.exports = PIX; else root.KRYPTA_PIX = PIX;\n"
          "})(typeof self !== 'undefined' ? self : this);\n")
    open(sys.argv[1], 'w', encoding='utf-8').write(js)
    print(len(data), 'frames ->', sys.argv[1], round(len(js) / 1024), 'KB')


if __name__ == '__main__':
    main()
